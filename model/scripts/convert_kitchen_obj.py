"""One-time conversion of the purchased kitchen environment asset
(model/kitchen/Kitchen.obj, a Blender-free SketchUp OBJ export) into a set
of small per-material STL meshes plus a color manifest that
urdf_to_mjcf.py's _build_kitchen_import() reads to place them in the MJCF --
the same "many small flat-colored STL parts" approach the robot's own CAD
meshes already use (see loadHumanoidScene.ts's own comment: this app's
three.js loader only ever reads flat rgba per geom, never a texture),
rather than trying to get MuJoCo/three.js to honor the OBJ's own 134
materials and UV-mapped textures directly.

Run once (`python3 model/scripts/convert_kitchen_obj.py`) after replacing
the source OBJ; output is checked in under model/kitchen/meshes/ like any
other static build input, not regenerated by urdf_to_mjcf.py itself.

This is the *second* kitchen asset this pipeline has imported (the first,
model/kitchen/new+kitchen.obj, is superseded and no longer referenced --
per the user's own explicit call: this new import is meant to fully replace
the old procedural room *and* the first imported kitchen, not sit alongside
either). Unlike the first import, this one supplies its own floor/walls/
ceiling (Stucco_A02_Color_50cm_White, Flooring_Parquet_Parallel_H01_120cm)
and is used as the *entire* room -- so there's no footprint-based shell
exclusion here the way the first conversion had one.

Why split by material at all instead of loading the OBJ directly: a MuJoCo
<mesh> asset is one set of vertices/faces with, at most, one <material> --
it has no notion of an OBJ's per-face `usemtl` switches. trimesh's
group_material=True loader merges every face in the whole file sharing a
material into one combined mesh regardless of which of the source file's
22904 named sub-objects/groups it came from (confirmed: this file has 134
newmtl entries and loading it this way yields exactly 134 geometries) --
i.e. one mesh per *color*, not per individual utensil/component, which is
what keeps the geom count low enough to stay interactive rather than
emitting a separate mesh per one of the ~1000s of small named parts.

Excluded materials (17 of 134, see _SKIP_MATERIALS): a "Sumele_*" human
figure (hair/skin/dress/shoe/jewelry) that never appears in any of the
reference renders (model/kitchen/kitchen-scene-*.webp) -- almost certainly
a stock entourage figure left in the source file but hidden/unused in the
actual rendered views -- and nine unused "*_Milgard" window color-swatch
variants (Espresso/Classic_Brown/Tan/Tweed/Clay/Silver/Sand/Bronze/Ivory/
Fog), each only 4 faces, bundled into the window component's own definition
but not the one actually applied (White_Milgard, at 2454 faces and a
footprint matching the visible window, clearly is -- kept).

Axis handling: this OBJ is Y-up (SketchUp's OBJ exporter convention,
confirmed by inspecting the raw vertex data), matching three.js's own
convention but not this app's MJCF-side convention (MuJoCo worldbody is
Z-up). mj_x=obj_x, mj_y=-obj_z, mj_z=obj_y is a proper rotation (determinant
+1, verified below), not a mirror, so winding order/normals need no extra
correction -- then the whole room is recentered so its own floor-plan
bounding box sits centered on the world origin (a real point inside an
actual room, unlike the first import which had to be offset against a
separate, since-removed procedural room's own south wall).
"""

