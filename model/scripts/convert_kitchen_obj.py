# The one real west-wall window (the fridge-side window the user kept
# reporting as "still looks like a wall", then "doesn't look like the window
# behind the stairs") has a genuine glass pane (White_Milgard_glass, split
# out above) sitting in its reveal -- but the room-facing surface of
# Stucco_A02_Color_50cm_White is a single ~22000-face merged mesh spanning
# every wall *and* the ceiling, and at this exact opening its own
# triangulation is broken: several of its fan-triangulated faces (all
# sharing one apex vertex out at y=4.4986,z=0.8763) sweep straight across
# the window's own rectangle instead of stopping at its edges, so an opaque
# white triangle sits directly between the room and the glass (confirmed by
# a manual ray-triangle cast from the live three.js scene: the nearest hit
# at the window's own screen position was this Stucco face, not the glass
# behind it). A first attempt papered over this with a small synthetic
# glass-colored patch flush with the wall -- structurally fine, but it also
# blocked the real glass's own mullion bars from showing through, which is
# exactly why this window read as a flat, undivided pane next to the
# working stairs window (same source geometry, no broken wall there) that
# has visible dividers. Real fix: clip the actual offending Stucco faces
# against the window's rectangle (2D polygon difference in the wall's own
# y-z plane, re-triangulated) so the room-facing wall has a genuine hole
# there instead of a patch in front of it -- see _cut_stucco_window_hole().
_STUCCO_WINDOW_HOLE_PLANE_X = -3.515
_STUCCO_WINDOW_HOLE_RECT_YZ = ((1.7413, 2.9596), (1.1808, 2.4000))


def _cut_stucco_window_hole(verts: np.ndarray, faces: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    (wy0, wy1), (wz0, wz1) = _STUCCO_WINDOW_HOLE_RECT_YZ
    window_rect = shapely_box(wy0, wz0, wy1, wz1)
    plane_x = _STUCCO_WINDOW_HOLE_PLANE_X

    on_plane = np.all(np.abs(verts[faces][:, :, 0] - plane_x) < 0.01, axis=1)
    candidate_idxs = set(np.where(on_plane)[0].tolist())

    out_verts = [verts]
    out_faces = []
    for i, face in enumerate(faces):
        if i not in candidate_idxs:
            out_faces.append(face)
            continue
        tri2d = verts[face][:, [1, 2]]
        poly = Polygon(tri2d)
        if not poly.is_valid or poly.area < 1e-9 or not poly.intersects(window_rect):
            out_faces.append(face)
            continue
        diff = poly.difference(window_rect)
        if diff.is_empty:
            continue  # this face's entire area is inside the window opening
        pieces = list(diff.geoms) if diff.geom_type == "MultiPolygon" else [diff]
        for piece in pieces:
            if piece.area < 1e-7:
                continue
            verts2d, tris = trimesh.creation.triangulate_polygon(piece, engine="earcut")
            base_idx = sum(len(vv) for vv in out_verts)
            out_verts.append(np.column_stack([np.full(len(verts2d), plane_x), verts2d]))
            for t in tris:
                out_faces.append(t + base_idx)

    return np.concatenate(out_verts), np.array(out_faces)


